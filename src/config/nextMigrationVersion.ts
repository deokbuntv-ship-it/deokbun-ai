// 새 마이그레이션 파일명 번호를 정한다 — **순서가 뒤집히는 것을 막는다.**
//
// WHY THIS EXISTS. ⚠ 이 레포에서 마이그레이션 번호는 **날짜가 아니라 순번**이다.
// 이력에 `20260832000000` ~ `20260847000000` 이 있다 — 8월 32일부터 47일까지는 없는 날짜다.
// 날짜로 읽으면 `supabase migration new` 가 붙이는 **현재 시각**으로 이름을 만들게 되는데,
// 레포 최대가 `20260915000000` 이라 오늘(2026-09-10) 시각으로 만들면 새 파일이 기존 파일보다
// **앞**에 끼어들고 `db push` 가 순서를 문제 삼는다.
//
// 규칙 (CTO 2026-09-10): **새 번호는 레포 최대 번호보다 크게.** 앞 8자리를 하나 올리고 뒤를
// 0 으로 둔다 — `20260915000000` → `20260916000000`. 같은 슬롯을 이미 쓰고 있으면 뒤 6자리를
// 100 씩 올린다(`…000100`), 레포가 `20260817000000/000100/000200/000300` 에서 쓰는 방식 그대로.
//
// ⚠ 현재 시각은 보지 않는다. 번호가 날짜가 아니므로 시계는 이 판단에 아무 정보도 주지 않는다.

const RE = /^\d{14}$/;

/** 파일명·버전 목록에서 14자리 번호만 골라 낸다. 앞 14자리만 본다. */
export function versionsOf(existing: readonly string[]): string[] {
  return existing.map((f) => f.slice(0, 14)).filter((v) => RE.test(v));
}

/**
 * 다음 마이그레이션 번호.
 *
 * @param existing 파일명이든 버전이든. 14자리가 아닌 것(README 등)은 무시한다.
 */
export function nextMigrationVersion(existing: readonly string[]): string {
  const versions = versionsOf(existing);
  // ⚠ 문자열 비교로 최댓값을 낸다. 14자리 고정폭이라 사전순 = 수치순이고,
  //   날짜가 아닌 번호(20260847000000)도 그대로 줄 세워진다.
  const max = versions.length > 0 ? versions.reduce((a, b) => (a >= b ? a : b)) : '20260817000000';
  // 앞 8자리를 하나 올리고 뒤를 0 으로. 뒤가 무엇이든 결과는 항상 max 보다 크다.
  return `${String(Number(max.slice(0, 8)) + 1).padStart(8, '0')}000000`;
}

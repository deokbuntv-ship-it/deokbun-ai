// 유명인 명식 해설 — 고지 문구와 시각 미상 정책. (S2, 2026-09-08)
//
// ⚠ 문구는 **우리 문장이다.** 경쟁 사이트가 같은 종류의 방어를 한다는 사실은 참고했지만 표현을
// 가져오지 않았다. 남의 문장을 베끼면 그 문장이 왜 그렇게 쓰였는지 모르는 채로 방어를 흉내 내게 되고,
// 조건이 달라졌을 때 고칠 근거가 없다.
//
// 고지가 담아야 하는 세 가지 (지시서 2-3):
//   ① 출생시각 정보 유무와 그로 인한 한계
//   ② 출생정보의 출처와 신뢰도 — `birthSource` 를 **실제로** 노출한다
//   ③ 이 콘텐츠의 성격 — 명식 해설이며 인물 평가가 아니다
//
// ⚠ 두 곳에 배치한다(본문 위 · 본문 아래). 위에 있어야 읽기 전에 알고, 아래에 있어야 다 읽고 나서도
// 남는다. 긴 글에서 상단 고지는 스크롤과 함께 사라진다.

/** 출생정보 출처 — 값은 DB 의 `birth_source` 그대로. */
export const BIRTH_SOURCE_LABEL: Record<string, string> = {
  confirmed: '본인 또는 공식 자료로 확인',
  reported: '언론 보도 등에서 확인',
  estimated: '알려진 정보로 추정',
  unknown: '출처 미상',
};

/** ③ 콘텐츠 성격 — 어느 인물에게나 같으므로 고정 문장이다. */
export const FAMOUS_NATURE_NOTICE =
  '이 글은 사주 명식(命式) 자체를 설명하는 학습용 글입니다. '
  + '특정 인물의 성격·능력·성취를 평가하거나 단정하지 않으며, 인물의 이력이나 사건과 연결하지 않습니다.';

/** 하단에 한 번 더 붙는 마무리. 상단 문장을 그대로 반복하지 않는다. */
export const FAMOUS_NATURE_NOTICE_FOOTER =
  '다시 한 번, 위 내용은 명식의 구조를 읽는 방법을 보여 주기 위한 것입니다. '
  + '같은 명식이라도 보는 관점과 살아온 환경에 따라 해석은 달라집니다. '
  + '사람을 판단하는 근거로 쓰지 말아 주세요.';

/**
 * ① + ② — 인물마다 달라지므로 계산해서 만든다.
 * `hourKnown` 은 **엔진이 시주를 세웠는가**이지 입력칸에 숫자가 있는가가 아니다.
 * (대략적인 시간대는 계산상 '모름'과 같다 — 엔진이 EXACT 만 시각으로 본다.)
 */
export function famousBirthNotice(params: {
  hourKnown: boolean;
  birthSource: string | null;
}): string {
  const source = BIRTH_SOURCE_LABEL[params.birthSource ?? 'unknown'] ?? BIRTH_SOURCE_LABEL.unknown;
  const time = params.hourKnown
    ? '태어난 시각까지 반영해 네 기둥을 모두 세웠습니다.'
    : '태어난 시각을 알 수 없어 **시주(時柱)를 세우지 않았습니다.** 여덟 글자 중 두 글자가 비어 있으므로, '
      + '시각을 알았을 때와 결론이 달라질 수 있습니다.';
  return `출생정보 출처: ${source}. ${time}`;
}

// ── 시각 미상 정책 (S2) ─────────────────────────────────────────────────────────────────────────
//
// (a) 시각 모름 + 경계일 아님 → 명식이 선다(시주만 없음). **콘텐츠 생성·발행 가능.**
//     유명인은 시각을 모르는 경우가 대부분이고, 그 상태로도 여섯 글자는 확정된다.
//     여섯 글자를 설명하는 것은 정직한 콘텐츠다 — 없는 두 글자를 안 만들기만 하면 된다.
//
// (b) 시각 모름 + 절기 경계일 → 월주가 두 후보. **명식 자체가 서지 않는다. 발행 불가.**
//     ⚠ 왜 "두 후보를 다 보여주기" 를 고르지 않았는가: **엔진이 두 후보를 주지 않는다.** 확정을
//     거부할 뿐이다. 후보를 만들려면 월주 귀속 규칙을 우리가 다시 구현해야 하고 그것은 계산 교리
//     창작이다(금지). 있지도 않은 선택지를 정책으로 적을 수는 없다.
//     ⚠ 왜 "등록 시점 차단" 이 아닌가: 운영자가 생년월일만 먼저 넣고 시각을 나중에 찾는 것이 정상적인
//     작업 순서다. 등록을 막으면 그 기록이 사라지고, 시각을 찾아도 처음부터 다시 넣어야 한다.
//     → **등록은 되고, 명식 계산이 실패로 기록되고, 본문 생성과 발행이 막힌다.**
//     명식이 없으면 설명할 것이 없다. 이름만 있는 페이지는 없는 페이지보다 나쁘다(빈약한 콘텐츠는
//     검색에도 감점이다).
//
// (c) 대략적인 시간대(오전/저녁) → 계산상 (a)와 동일. 엔진이 EXACT 만 시각으로 취급한다(측정됨).

export const FAMOUS_CHART_BLOCKED_NOTICE =
  '이 생년월일은 사주의 달이 바뀌는 절기 경계일이라, 태어난 시각을 모르면 월주(月柱)가 두 가지로 갈립니다. '
  + '명식을 확정할 수 없어 해설을 만들지 않습니다. 정확한 태어난 시각을 넣으면 바로 생성할 수 있습니다.';

/** 발행 가능 여부. 명식이 없으면 발행하지 않는다 — 설명할 것이 없기 때문이다. */
export function canPublishFamous(calculationState: string | null | undefined): boolean {
  return calculationState === 'current';
}
